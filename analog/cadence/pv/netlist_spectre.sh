#!/usr/bin/env bash
# =====================================================================
# netlist_spectre.sh -- Spectre netlist of one cell as "subckt <CELL> ...
# ends" plus every subckt below it, for the AMS flow's `config ... use=spice`.
#
# Usage:
#   ./netlist_spectre.sh <LIB> <CELL> <OUT.scs> [VIEW ...]
# VIEW list = the netlister's switch view list (default:
#   spectre cmos_sch cmos.sch schematic veriloga). Put av_extracted first to
#   netlist a Quantus extracted view instead of the schematic.
#
# Netlisting a cell directly emits its contents with no subckt wrapper, so a
# one-instance wrapper schematic is built in a scratch library and netlisted
# instead; only the subckt blocks are kept. Devices bind through the PDK's
# spectre views (nfet_01v8, cap_mim_m3_1, ...), the same names as the sky130
# model files, which the LVS CDL (cap_mim_m3__base) does not give.
#
# Env: CDSLIB (default ../cds.lib), RUNDIR (default runs/netlist/<CELL>).
# =====================================================================
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CDSLIB="${CDSLIB:-$SCRIPT_DIR/../cds.lib}"
[ $# -ge 3 ] || { sed -n '2,19p' "$0"; exit 2; }
LIB="$1" CELL="$2" OUT="$3"; shift 3
VIEWS="${*:-spectre cmos_sch cmos.sch schematic veriloga}"
case "$OUT" in /*) ;; *) OUT="$PWD/$OUT";; esac
RUN="${RUNDIR:-$SCRIPT_DIR/runs/netlist/$CELL}"
export LC_ALL="${LC_ALL:-en_US.utf8}" LANG="${LANG:-en_US.utf8}" CDS_Netlisting_Mode=Analog
command -v virtuoso >/dev/null || { echo "ERROR: virtuoso not on PATH" >&2; exit 2; }

rm -rf "$RUN"; mkdir -p "$RUN"; cd "$RUN"
echo "INCLUDE $(cd "$(dirname "$CDSLIB")" && pwd)/$(basename "$CDSLIB")" > cds.lib
VLIST=$(for v in $VIEWS; do printf '"%s" ' "$v"; done)
cat > nl.il <<EOF
let((cv sym inst)
  unless(ddGetObj("nl_scratch") ddCreateLib("nl_scratch" "$RUN/nl_scratch"))
  sym = dbOpenCellViewByType("$LIB" "$CELL" "symbol" nil "r")
  unless(sym error("no symbol for $LIB/$CELL"))
  cv = dbOpenCellViewByType("nl_scratch" "${CELL}_wrap" "schematic" "schematic" "w")
  inst = dbCreateInst(cv sym "XDUT" 0:0 "R0")
  ; stub each pin outward from the side of the symbol it sits on, so that
  ; stubs of neighbouring pins can never touch
  foreach(term sym~>terminals
    let((xy b dx dy p2 w)
      xy = dbTransformPoint(centerBox(car(term~>pins)~>fig~>bBox) inst~>transform)
      b = inst~>bBox
      dx = car(xy) - (caar(b) + caadr(b)) / 2.0
      dy = cadr(xy) - (cadar(b) + cadadr(b)) / 2.0
      p2 = if(abs(dx) * (cadadr(b) - cadar(b)) >= abs(dy) * (caadr(b) - caar(b))
             then list(car(xy) + if(dx < 0 -0.25 0.25) cadr(xy))
             else list(car(xy) cadr(xy) + if(dy < 0 -0.25 0.25)))
      w = schCreateWire(cv "draw" "full" list(xy p2) 0.0625 0.0625 0.0)
      schCreateWireLabel(cv car(w) p2 term~>name "lowerLeft" "R0" "stick" 0.0625 nil)))
  schCheck(cv) dbSave(cv) dbClose(cv))
envSetVal("asimenv.startup" "projectDir" 'string "$RUN/sim")
simulator('spectre)
design("nl_scratch" "${CELL}_wrap" "schematic")
envOption('switchViewList '($VLIST))
envOption('stopViewList '("spectre"))
printf("NLPATH %L\n" createNetlist(?recreateAll t ?display nil))
exit()
EOF
virtuoso -nograph -replay nl.il -log nl.log > /dev/null 2>&1 || true
NL=$(sed -n 's/^\\o NLPATH "\(.*\)"$/\1/p' nl.log | head -1)
[ -n "$NL" ] && [ -f "$NL" ] || { grep -E '^\\e|ERROR \(|Error: \(' nl.log | head || true; echo "ERROR: netlisting failed (see $RUN/nl.log)" >&2; exit 3; }
{ echo "// GENERATED by analog/cadence/pv/netlist_spectre.sh from OA $LIB/$CELL"
  echo "// view list: $VIEWS -- do not edit by hand"
  awk '/^subckt /{p=1} p{print} /^ends /{p=0}' "$NL"; } > "$OUT"
grep -q "^subckt $CELL " "$OUT" || { echo "ERROR: no 'subckt $CELL' in $NL" >&2; exit 3; }
echo "    $OUT: $(grep -c '^subckt ' "$OUT") subckts, $(wc -l < "$OUT") lines"
